# -*- coding: utf-8 -*-
"""
无人机状态机枚举 —— 对应任务3 要求"文字方式显示无人机实时状态
(伴飞、抛投、降落、起飞等)"。

覆盖任务1(伴飞抛投)和任务2(动态起降)两条链的所有阶段。
每个状态带中文显示名和一个用于地面站配色的标识色(RGB)。
"""
from enum import Enum


class DroneState(Enum):
    IDLE      = ("待命",   (120, 120, 120))   # 未起飞
    TAKEOFF   = ("起飞中", (30, 140, 220))    # H点垂直起飞→150cm
    HOVER     = ("悬停中", (30, 140, 220))    # 150±10cm 稳定悬停(任务1 起飞后停3s)
    SEARCH    = ("搜索中", (200, 150, 0))     # 巡航寻找小车(任务2)
    FOLLOW    = ("伴飞中", (0, 160, 60))       # 跟随小车,维持相对位置
    DROP      = ("抛投",   (220, 60, 180))     # 舵机松爪投放
    DESCEND   = ("降落中", (200, 90, 0))       # 降落到小车平台(任务2)/降落H
    ONBOARD   = ("平台停留",(150, 90, 200))    # 落在小车平台上停留5s(任务2)
    RETURN    = ("返航中", (0, 120, 180))      # 回H点上方
    LANDING_H = ("降落起降点",(200, 90, 0))    # 视觉落桩回H
    LANDED    = ("已降落", (80, 160, 80))      # 任务完成
    ERROR     = ("异常",   (200, 30, 30))      # 触地/失联等

    def __init__(self, label, color):
        self.label = label
        self.color = color
